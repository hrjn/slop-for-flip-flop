export const CHAR_WIDTH = 5;
export const CHAR_HEIGHT = 7;

const FALLBACK = GLYPHS["?"] as readonly string[];

const glyph = (char: string): readonly string[] =>
  GLYPHS[char] ?? GLYPHS[char.toUpperCase()] ?? FALLBACK;

export const hasGlyph = (char: string): boolean =>
  GLYPHS[char] !== undefined || GLYPHS[String(char).toUpperCase()] !== undefined;

export const textWidth = (text: string, scale = 1, tracking = 1): number =>
  text.length === 0
    ? 0
    : text.length * (CHAR_WIDTH + tracking) * scale - tracking * scale;

export interface TextOptions {
  color?: string;
  scale?: number;
  tracking?: number;
  shadow?: number;
  shadowColor?: string;
  align?: "left" | "center" | "right";
}

/** Draw text in game pixels (1 unit = 1 game pixel). Returns the width it occupied. */
export const drawText = (
  ctx: CanvasRenderingContext2D,
  value: string | number,
  x: number,
  y: number,
  options: TextOptions = {}
): number => {
  const {
    scale = 1,
    tracking = 1,
    color = "#ffffff",
    shadow = 0,
    shadowColor = "#000000",
    align = "left",
  } = options;

  const text = String(value);
  const width = textWidth(text, scale, tracking);
  const originX =
    align === "center"
      ? Math.round(x - width / 2)
      : align === "right"
        ? Math.round(x - width)
        : x;

  for (let pass = 0; pass < (shadow ? 2 : 1); pass++) {
    const isShadow = shadow > 0 && pass === 0;
    ctx.fillStyle = isShadow ? shadowColor : color;
    const offset = isShadow ? shadow * scale : 0;
    let cursor = originX;

    for (const char of text) {
      const rows = glyph(char);

      for (let ry = 0; ry < CHAR_HEIGHT; ry++) {
        const row = rows[ry] ?? "";
        let runStart = -1;

        for (let rx = 0; rx <= CHAR_WIDTH; rx++) {
          const on = rx < CHAR_WIDTH && row[rx] === "#";

          if (on && runStart < 0) {
            runStart = rx;
          }

          if (!on && runStart >= 0) {
            ctx.fillRect(
              cursor + runStart * scale + offset,
              y + ry * scale + offset,
              (rx - runStart) * scale,
              scale
            );
            runStart = -1;
          }
        }
      }

      cursor += (CHAR_WIDTH + tracking) * scale;
    }
  }

  return width;
};
